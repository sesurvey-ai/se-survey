import { getIO } from '../socket';

/**
 * แจ้งหน้าเว็บว่า "เคสนี้เปลี่ยนไปแล้ว" — ให้คิวงานตรวจอัปเดตเองโดยไม่ต้องกด F5
 *
 * ทำไมต้องมี: หน้าคิวโหลดครั้งเดียวตอนเปิด พอมีหัวหน้าตรวจหลายคน (แผนคือ 8 คน)
 * แต่ละคนเห็นภาพคนละเวลา — เปิดเรื่องที่คนอื่นตรวจจบไปแล้ว หรือไม่เห็นงานใหม่ที่เพิ่งเข้ามา
 * จนกว่าจะบังเอิญกดรีเฟรช
 *
 * ⛔ เป็นแค่ "สัญญาณเตือน" ไม่ได้ส่งข้อมูลเคสมาด้วย — หน้าเว็บต้องไปดึงเองผ่าน API ปกติ
 *    (ไม่งั้นต้องมาดูแลสิทธิ์การเห็นข้อมูลซ้ำอีกที่หนึ่งบน socket ซึ่งพลาดง่าย)
 *
 * ⛔ ห้ามให้หน้ารายละเอียดเคส "โหลดใหม่ให้เอง" เมื่อได้สัญญาณนี้ — ผู้ตรวจอาจพิมพ์ค้างอยู่
 *    หน้านั้นทำได้แค่ขึ้นป้ายเตือนให้คนตัดสินใจเอง (ดู CaseDetail)
 */
export type CaseChangeReason =
  | 'submitted'      // ผู้สำรวจส่งงานเข้ามา
  | 'finished'       // ผู้สำรวจกด "เสร็จงาน" หน้างาน (ยังไม่ส่ง — บอร์ดจ่ายงาน/คิวตรวจอัปเดตป้าย)
  | 'saved'          // ผู้ตรวจกดบันทึก
  | 'approved'       // อนุมัติ
  | 'sent_back'      // ตีกลับให้ผู้สำรวจ
  | 'unlocked'       // แอดมินปลดล็อก
  | 'imported'       // สร้างเคสจากไฟล์ XML / ดึงจากระบบเก่า
  | 'emcs'           // บอทรายงานสถานะฝั่งระบบประกัน
  | 'isurvey'        // เขียนกลับ ISURVEY (ปิดงานหลังอนุมัติ) สำเร็จ/ล้มเหลว — หน้าเคสโชว์ป้ายใหม่
  | 'emcs_queue'     // คิวนำเข้า EMCS เปลี่ยนสถานะ (เข้าคิว/สถานีรับ/เสร็จ/พัง/ยกเลิก)
  | 'deleted'        // แอดมินลบแบบพักไว้ (ถังขยะ) — ทุกรายการต้องเอาเคสนี้ออก (14/09/69)
  | 'restored';      // กู้คืนจากถังขยะ — กลับมาในรายการตามสถานะเดิม

/** @param by id ของคนที่ทำ — หน้าเว็บใช้ข้ามสัญญาณที่เกิดจากตัวเอง (ไม่ต้องเตือนตัวเอง) */
export function notifyCaseChanged(
  caseId: number, reason: CaseChangeReason, by?: number | null,
): void {
  const io = getIO();
  if (!io) return;   // รันโหมดที่ไม่มี socket (เทส/สคริปต์) — ไม่ใช่เรื่องผิดปกติ
  // socket.io ส่งซ้ำไม่ได้แม้อยู่หลายห้อง — คนที่เป็นทั้ง admin และ checker ได้ครั้งเดียว
  io.to('role:checker').to('role:admin').to('role:callcenter')
    .emit('case_changed', { case_id: caseId, reason, by: by ?? null });
}

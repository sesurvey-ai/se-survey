/**
 * เบอร์โทรพนักงาน (users.phone) — ใช้ร่วมกัน 3 ที่: ตารางผู้ใช้ (แสดงเบอร์) · หน้าเพิ่มผู้ใช้ · หน้าแก้ไขผู้ใช้ (กรอก/แก้เบอร์)
 * เก็บเป็นตัวเลขล้วน (ทะเบียนจริงเป็น 10 หลักทุกคน) — พิมพ์ขีด/เว้นวรรคมาได้ ตัดทิ้งตอนบันทึก
 * แอปมือถือเติมช่อง "โทรศัพท์สำรวจ" (ช่องบังคับของ EMCS) จากเบอร์นี้
 */

/** ตัดให้เหลือตัวเลข เช่น '096-9829655' → '0969829655' */
export const phoneDigits = (p?: string | null) => (p || '').replace(/\D/g, '');

/** ข้อความผิดพลาด หรือ '' ถ้าใช้ได้ (ว่าง = ไม่มีเบอร์ ใช้ได้) */
export const phoneError = (p?: string | null) => {
  const d = phoneDigits(p);
  return d && (d.length < 9 || d.length > 10) ? 'เบอร์โทรต้องเป็นตัวเลข 9–10 หลัก (เช่น 0812345678)' : '';
};

/** เบอร์ 10 หลัก → 0xx-xxx-xxxx · อย่างอื่นโชว์ตามที่เก็บ */
export const fmtPhone = (p?: string | null) => {
  const d = phoneDigits(p);
  return d.length === 10 ? `${d.slice(0, 3)}-${d.slice(3, 6)}-${d.slice(6)}` : (p || '—');
};
